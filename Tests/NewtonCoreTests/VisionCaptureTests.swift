import Testing
import Foundation
import CoreGraphics
@testable import NewtonCore

struct VisionCaptureTests {

    final class MockFrameProvider: ScreenFrameProviding, @unchecked Sendable {
        var image: CGImage?
        init(image: CGImage? = nil) { self.image = image }
        func captureDisplayImage() -> CGImage? { image }
    }

    final class MockRecognizer: TextRecognizing, @unchecked Sendable {
        var stubbedLines: [RecognizedTextLine]
        init(lines: [RecognizedTextLine] = []) { self.stubbedLines = lines }
        func recognizeText(in image: CGImage) throws -> [RecognizedTextLine] { stubbedLines }
    }

    static func makeTestImage(width: Int = 50, height: Int = 50) -> CGImage? {
        let colorSpace = CGColorSpaceCreateDeviceRGB()
        var rawData = [UInt8](repeating: 255, count: width * height * 4)
        guard let context = CGContext(
            data: &rawData,
            width: width,
            height: height,
            bitsPerComponent: 8,
            bytesPerRow: width * 4,
            space: colorSpace,
            bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue
        ) else { return nil }
        return context.makeImage()
    }

    @Test func testRecognizedScreenFrameConvertsToValidHistoryEvent() throws {
        let lines = [
            RecognizedTextLine(text: "Newton Workspace", confidence: 0.95, boundingBox: [0.1, 0.9, 0.4, 0.05]),
            RecognizedTextLine(text: "Active Tasks: 3", confidence: 0.88, boundingBox: [0.1, 0.8, 0.3, 0.04])
        ]
        let frame = RecognizedScreenFrame(
            appName: "Newton",
            windowTitle: "Main Dashboard",
            fullText: "Newton Workspace\nActive Tasks: 3",
            lines: lines
        )

        let event = frame.asHistoryEvent()
        #expect(event.source == "Newton · Main display OCR")
        #expect(event.title == "Newton — Main Dashboard")
        #expect(event.detail.contains("Newton Workspace"))
        #expect(event.detail.contains("Active Tasks: 3"))

        // Must pass EventStore validation
        try EventStore.validate(event)
    }

    @Test func testVisionCaptureEngineExtractsFrameFromImage() async throws {
        let testImage = Self.makeTestImage()
        let provider = MockFrameProvider(image: testImage)
        let recognizer = MockRecognizer(lines: [
            RecognizedTextLine(text: "git commit -m \"Phase 1\"", confidence: 0.99, boundingBox: [0.05, 0.95, 0.5, 0.04]),
            RecognizedTextLine(text: "[main 2ba353a] passed", confidence: 0.92, boundingBox: [0.05, 0.85, 0.4, 0.04])
        ])

        let engine = VisionCaptureEngine(recognizer: recognizer, frameProvider: provider)
        let captured = try await engine.captureFrame(appName: "Terminal", windowTitle: "zsh")

        #expect(captured != nil)
        #expect(captured?.appName == "Terminal")
        #expect(captured?.windowTitle == "zsh")
        #expect(captured?.lines.count == 2)
        let text = captured?.fullText ?? ""
        #expect(text.contains("git commit"))
    }

    @Test func testVisionCaptureEngineHandlesNilFrameGracefully() async throws {
        let provider = MockFrameProvider(image: nil)
        let recognizer = MockRecognizer(lines: [])
        let engine = VisionCaptureEngine(recognizer: recognizer, frameProvider: provider)

        let captured = try await engine.captureFrame(appName: "Finder")
        #expect(captured == nil)
    }

    @Test func testEmbeddedScreenpipeClientSearchesLocalStoreDirectly() async throws {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tempDir) }

        let store = try EventStore(path: tempDir.appendingPathComponent("test.sqlite").path)

        // Insert an OCR event generated by VisionCaptureEngine
        let frame = RecognizedScreenFrame(
            appName: "Xcode",
            windowTitle: "NewtonCore",
            fullText: "func buildSuperApp() -> Void // Personal SuperApp Workspace",
            lines: [RecognizedTextLine(text: "func buildSuperApp() -> Void // Personal SuperApp Workspace", confidence: 0.99)]
        )
        try await store.append([frame.asHistoryEvent()])

        // Embedded searcher searches local store with sub-millisecond latency
        let client = EmbeddedScreenpipeClient(store: store)
        let result = try await client.search("SuperApp")

        #expect(result.events.count == 1)
        #expect(result.events[0].title.contains("Xcode"))
        #expect(result.events[0].detail.contains("buildSuperApp"))
        #expect(result.omitted == 0)
    }

    @Test func testEmbeddedScreenpipeClientReturnsEmptyWhenNoMatchAndNoToken() async throws {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: tempDir) }

        let store = try EventStore(path: tempDir.appendingPathComponent("test.sqlite").path)
        let client = EmbeddedScreenpipeClient(store: store)

        let result = try await client.search("NonexistentKeyword12345")
        #expect(result.events.isEmpty)
        #expect(result.omitted == 0)
    }
    @Test func embeddedSearchPropagatesFailureEvenWithExternalToken() async {
        let local = EmbeddedScreenpipeClient(storeProvider: { throw StoreError(message: "local fixture failure") })
        await #expect(throws: StoreError.self) { try await local.search("query", token: "external-token") }
    }
}
